export function debounce<T extends (...args: never[]) => void>(fn: T, ms: number): T {
  let t: ReturnType<typeof setTimeout> | undefined;
  return ((...args: never[]) => {
    if (t) clearTimeout(t);
    t = setTimeout(() => fn(...args), ms);
  }) as T;
}

export const prefersReducedMotion = (): boolean =>
  typeof window !== 'undefined' && window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;

/** Drop null/false entries so a list can be passed to replaceChildren/append. */
export function nodes(...a: (Node | string | null | undefined | false)[]): (Node | string)[] {
  return a.filter((x): x is Node | string => x !== null && x !== undefined && x !== false);
}
